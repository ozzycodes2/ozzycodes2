"""The hand-written content and the vendored rosters, read off disk.

Four files, all of them reviewed in a diff rather than fetched:

  profile.toml          prose — headline, tagline, project blurbs
  stack.json            category -> tool -> pedestal level 1-5, in draw order
  languages.json        language -> bytes, the polar ring in `~/stack`
  logos/stack-logos.json  brand marks for the roster above

Each roster is its own file because TOML cannot express it: a mapping from name
to number, where a table inside `[stack]` would put every category on four lines
of header. Key order is draw order, top category first.

`languages.json` is curated rather than fetched. `data/stats.json` still carries
what the API reports, but whole-tree byte counts answer a question nobody asked
— which checkout is largest, not which languages the work is in — and a single
generated monorepo can be half the total. Edit the file to change the chart.
"""
import json
import pathlib
import tomllib

PROFILE = pathlib.Path(__file__).resolve().parent.parent
LOGO_DIR = PROFILE / "logos"


def profile_config():
    """profile.toml, parsed."""
    return tomllib.loads((PROFILE / "profile.toml").read_text())


def stack_roster():
    return json.loads((PROFILE / "stack.json").read_text())


def languages():
    return json.loads((PROFILE / "languages.json").read_text())


def stack_logos():
    """Brand marks for the stack roster.

    Generated by design-preview's `vendor_logos.py` from Simple Icons (CC0 1.0)
    and Devicon (MIT); see logos/README.md. A tool with no entry falls back to
    mono type at its cell's centre, so adding one to the roster without
    vendoring its mark degrades rather than breaks.
    """
    return json.loads((LOGO_DIR / "stack-logos.json").read_text())
