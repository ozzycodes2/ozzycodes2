def _round(value):
    """Round half away from zero, the way `Math.round` does in the preview."""
    return math.floor(value + 0.5)


def _n(value):
    """A coordinate, at the two decimals the projection emits."""
    v = _round(value * 100) / 100
    return int(v) if v == int(v) else v


def legible(color, ground, ink, minimum):
    """Pull `color` toward `ink` until it clears `minimum` against `ground`.

    Fifty 2% steps, so a hex that only just misses is corrected by an amount
    nobody can see and a hex that cannot be rescued ends at the ink rather than
    looping.
    """
    out = color
    for w in range(51):
        if c.contrast(out, ground) >= minimum:
            break
        out = c.mix(ink, color, w / 50)
    return out


def brand(theme, hexa, ground):
    """A brand hex, corrected until it can be seen on the face it lands on.

    3:1 is the graphical-object threshold, and these are objects rather than
    words. Holding them to the 4.5:1 a word needs would drag every light mark
    most of the way to the ink and undo the reason they carry their own colour.
    """
    return legible(hexa, ground, theme.ink, 3)


def focal_tint(theme, lift=0.0):
    """The accent-over-canvas ratio a focal face takes at a given lift.

    Solved rather than declared. A neutral cell separates from the slab it
    stands on by one 10% ink step, and the same step in accent-over-canvas is
    worth far less — the ramp from canvas to accent is shorter than the ramp
    from surface to ink, and on light paper much shorter. Declaring the step
    leaves the marks on the focal layer sitting on nothing, so this matches the
    ratio the neutral slabs get for free and lets the step fall out of it. That
    is also what holds the figure in both polarities, where the two ramps are
    short by different amounts.
    """
    base = 0.18 if theme.name == "dark" else 0.14
    if not lift:
        return base
    want = c.contrast(c.mix(theme.ink, theme.surface, lift), theme.surface)
    face = c.mix(theme.accent, theme.canvas, base)
    o = base
    while o < 1:
        if c.contrast(c.mix(theme.accent, theme.canvas, o), face) >= want:
            return o
        o += 0.01
    return 1.0


def faces(theme, focal, lift=0.0):
    """(base, top, left, right, rule) paints for one part.

    Opaque base plus a solid mix, never a translucent fill — a part behind would
    otherwise show through the one in front of it. Light comes from the top
    left, so the left wall is lighter than the right; an unshaded outline box
    flips like a Necker cube.

    The two walls are one 5% ink step apart, which is the least that still turns
    the corner. Any more and the join reads as a drawn line rather than as a
    solid turning, which is the thing the silhouette stroke was already pulled
    off the ink to avoid.

    `lift` raises a part off the one it stands on: a cell takes more ink than
    its slab, lighter on the dark canvas and darker on the light one, which is
    how the rise reads with no shadow under it. Its own walls are then one step
    off its own face, so the focal slab's parts are shaded in the same ratios as
    the neutral ones.

    `rule` is the system hairline rather than the ink, so the join between two
    faces is carried by the step in their mixes. An ink outline flips polarity
    with the canvas and draws a hard white or black seam down every corner,
    which is the one mark in the figure that would read as a line rather than as
    a solid turning.
    """
    base = (c.mix(theme.accent, theme.canvas, focal_tint(theme, lift)) if focal
            else c.mix(theme.ink, theme.surface, lift))
    return (base, base, c.mix(theme.ink, base, 0.05), c.mix(theme.ink, base, 0.1),
            theme.hairline)


def rise_of(level):
    """How tall a pedestal stands, from its tool's level in stack.json.

    The level is the one number the roster carries beyond the name, so it is the
    one thing the figure can say about a tool without a second label. Out of
    range clamps rather than raising: the roster is hand-authored, and a figure
    that silently flattens one pedestal is a better failure than a panel that
    does not render.
    """
    try:
        lvl = min(max(_round(float(level)), 1), TILE_LEVELS)
    except (TypeError, ValueError):
        lvl = 1
    return TILE_RISE + (lvl - 1) * TILE_STEP


# The tallest pedestal the ladder allows, which is what the gap is cut for — not
# the tallest in the roster. Levels are content, and a gap that tracked them
# would resize the whole figure every time one tool moved a step.
RISE_MAX = rise_of(TILE_LEVELS)


def project(ox, oy):
    """2:1 dimetric, bound to one figure's origin.

    World x runs right and down, y left and down, z up. A model coordinate on a
    multiple of 2 lands on a whole pixel. Never place a projected point by hand.
    """
    return lambda x, y, z: (_n(ox + x - y), _n(oy + (x + y) / 2 - z))


def foot_outline(w, d, r, seg=ARC_SEG):
    """Model-space outline of a rounded-rect footprint.

    Sampled forward from the y = 0 edge, so the walk runs right extreme, front
    corner, left extreme, back corner. Straight edges are implicit: consecutive
    arc endpoints are the ends of one, and a polygon joins them with the line
    that edge already is.

    A circle of radius r in the xy plane projects to an axis-aligned ellipse of
    rx = r*sqrt(2) and ry = r/sqrt(2), so a corner is one arc of one ellipse.
    Sampling it rather than emitting an `A` keeps every face a polygon, and the
    shape is the same shape — which is also why a footprint whose radius is half
    its width needs no second primitive to be a cylinder.
    """
    pts = []
    for cx, cy, a0 in ((w - r, r, -90), (w - r, d - r, 0), (r, d - r, 90), (r, r, 180)):
        for i in range(seg + 1):
            a = math.radians(a0 + 90 * i / seg)
            pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


def foot_bounds(out):
    """The three outline indices that set a prism's silhouette.

    The left and right screen extremes, where its side walls stand, and the
    front corner, where the lit and shaded walls meet. Rounding moves all three
    onto the corner arcs, so none of them is a literal corner of the rectangle.
    """
    def peak(f):
        return max(range(len(out)), key=lambda i: f(*out[i]))

    return {"right": peak(lambda x, y: x - y),
            "front": peak(lambda x, y: x + y),
            "left": peak(lambda x, y: y - x)}


def prism(pr, box, paint, stroke=c.EDGE_W):
    """One rounded prism: the silhouette, the top face, and the two front walls.

    `box` is (x, y, w, d, r, z, h) in model space. Connector rule 1 admits only
    an axis-aligned line and every dimetric edge here is polygon geometry, so
    there are no strokes inside the part: the two walls meet at the front corner
    on the step between their mixes.
    """
    x, y, w, d, r, z, h = box
    out = [(x + px, y + py) for px, py in foot_outline(w, d, r)]
    b = foot_bounds(out)
    base, top, left, right, rule = paint
    zt = z + h

    def walk(start, end, lift):
        pts, i = [], start
        while True:
            pts.append(pr(out[i][0], out[i][1], lift))
            if i == end:
                return pts
            i = (i + 1) % len(out)

    def poly(pts):
        return " ".join(f"{px},{py}" for px, py in pts)

    def wall(start, end, fill):
        pts = walk(start, end, zt) + walk(start, end, z)[::-1]
        return f'<polygon points="{poly(pts)}" fill="{fill}"/>'

    # The back half along the top and the front half along the bottom: the two
    # joins, at the left and right extremes, are the vertical side edges.
    sil = poly(walk(b["left"], b["right"], zt) + walk(b["right"], b["left"], z))
    lid = poly(walk(b["left"], (b["left"] - 1) % len(out), zt))
    return "\n".join([
        f'<polygon points="{sil}" fill="{base}"/>',
        f'<polygon points="{lid}" fill="{top}"/>',
        wall(b["front"], b["left"], left),
        wall(b["right"], b["front"], right),
        f'<polygon points="{sil}" fill="none" stroke="{rule}" '
        f'stroke-width="{stroke}" stroke-linejoin="round"/>',
    ])


def tile_side(n, fan):
    """Cells a side, for the two placements.

    The top layer is the only one nothing stands over, so it uses the whole
    lattice and needs k^2 positions. Every layer under one uses the near border
    only — the two edges facing the viewer, 2k-1 positions, or one fewer when
    the count is even, because an even roster leaves the front corner empty to
    stay symmetric about it.

    Both are the figure's capacity rather than a preference: past it the lattice
    densifies and the cells shrink, but the footprint and the gap do not, so the
    slice's height stays a property of the frame rather than of the roster.
    """
    if fan:
        want = math.ceil(math.sqrt(n))
    else:
        want = (n + 1) // 2 if n % 2 else n // 2 + 1
    return max(TILE_SIDE, want)


def tile_size(w, d, side):
    """The largest cell that keeps a `side`-wide lattice inside this footprint."""
    span = min(w, d) - 2 * TILE_PAD - (side - 1) * TILE_CLEAR
    return max(10, span // side)


def tile_cells(side, w, d, g, n, fan):
    """Where a layer's tools stand, on a square lattice centred on its top face.

    The lattice is axis-aligned in model space, which is what makes the run read
    as lying on the face and turning with it: a g x g cell projects to a rhombus
    2g wide and g tall. The pitch has to clear g rather than g/2 — two cells an
    offset of (p, p/2) apart in screen space come apart only at p >= g, so the
    space between them is the pitch minus the cell, not half of it.

    `fan` fills the lattice by screen rows from the front, centring the row that
    runs out. A line of constant i + j projects to a screen row, so the rows come
    1, 2, 3 outward from the front corner and six tools land as the front half of
    a 3x3 exactly. Only the top layer can be filled this way; under a slab the
    back of the face is covered at the spacing this figure stacks at.

    Otherwise only the near border is used, walked outward from the front corner
    in pairs so the run stays symmetric — an odd count takes the corner itself
    and an even one does not.
    """
    p = g + TILE_CLEAR
    span = (side - 1) * p + g
    x0, y0 = (w - span) / 2, (d - span) / 2
    far = side - 1
    slots = []

    if fan:
        for s in range(2 * far, -1, -1):
            if len(slots) >= n:
                break
            row = [(i, s - i) for i in range(far, -1, -1) if 0 <= s - i <= far]
            take = min(len(row), n - len(slots))
            start = (len(row) - take) // 2
            slots += row[start:start + take]
    else:
        if n % 2:
            slots.append((far, far))
        for s in range(1, side):
            if len(slots) >= n:
                break
            slots += [(far, far - s), (far - s, far)]

    return [(x0 + i * p, y0 + j * p) for i, j in slots[:n]]


def face_tiles(pr, ox, oy, zt, items, cells, paint, *, g, round_cells, corner, theme):
    """One raised cell per tool on a layer's top face, each carrying its mark.

    A part made of many identical pieces declares the envelope of its grid as
    its own box and paints one small prism per piece. That is what gives the
    surface depth: the tools are objects standing on the layer, not a pattern
    printed across it. An unused lattice position is not drawn — a blank cell is
    a tool the panel is claiming and does not have.

    `round_cells` draws cylinders instead of squares, which is the one thing
    that tells the tooling tray apart from the three layers it carries. A square
    cell takes its slab's corner as a proportion of width, so every square in the
    figure turns at one radius-to-width ratio and the cells read as the slab's
    own parts rather than as a second kind of box.

    `matrix(1,0.5,-1,0.5,ox,oy-lid)` is the one matrix that agrees with the
    projection for a face at that height, so a glyph drawn in plain face
    coordinates lands on the cell with nothing placed by hand. A tool with no
    vendored mark is the exception: a word never takes the matrix, so it is set
    horizontally at its cell's projected centre.
    """
    placed = [(x, y, name, rise_of(level)) for (x, y), (name, level) in zip(cells, items)]
    # Back to front, or a cell paints over the one standing behind it.
    placed.sort(key=lambda t: t[0] + t[1])

    out = []
    for x, y, name, rise in placed:
        r = g / 2 if round_cells else corner
        out.append(prism(pr, (x, y, g, g, r, zt, rise), paint, CELL_EDGE))

        logo = LOGOS.get(name)
        if not logo:
            cx, cy = pr(x + g / 2, y + g / 2, zt + rise)
            out.append(c.tx(cx, cy + 4, name, fill=theme.dim, family=c.MONO_STACK,
                            size=11, ls=0.5, anchor="middle"))
            continue
        # Inscribed, not inset: the largest square inside a circle of diameter g
        # has side g/sqrt(2), so a round cell gives up a seventh of its width.
        inset = _round(g * (0.16 if round_cells else 0.13))
        # Four places, rounded half away from zero. A cell 28 units wide inset by
        # 4 against a 128-unit viewBox lands on exactly 0.15625, and Python's
        # round would take that to even while the preview's toFixed takes it up.
        scale = _round((g - 2 * inset) / logo["box"] * 10000) / 10000
        flat = f"matrix(1,0.5,-1,0.5,{_n(ox)},{_n(oy - zt - rise)})"
        out.append(
            f'<g transform="{flat}"><g transform="translate({_n(x + inset)} '
            f'{_n(y + inset)}) scale({scale:.4f})">'
            f'<path d="{logo["d"]}" fill="{brand(theme, logo["hex"], paint[1])}"/></g></g>')
    return "\n".join(out)


def polar_layout(languages, cats, r):
    """Languages by bytes as a polar ring: angle is rank, radius is share.

    Rank is not a cycle, which is the one thing this type asks of its
    categories. What the ring buys in exchange is the shape of the fall, which a
    row of bars states one bar at a time.

    `cats` is how many sectors the ring is cut into, 4 to 8. A roster longer than
    the cut folds its tail into a single `other`, so the remainder is accounted
    for without spending a sector on each member of it; a roster shorter than the
    cut draws one sector per language and no fold. The scale runs 0 to the
    leading share rounded up to the next tenth, so every ring is a tenth of the
    whole and the leader terminates inside the outermost one.

    Per-ring numerals are dropped against the type's layout conventions: five of
    them up the twelve o'clock axis at this console's smallest mono would sit
    under the twelve o'clock ray, and every category already carries its own
    number. The ring carries no caption either — it shares the slice's heading
    with the figure, and `desc` is where the measure is named.

    Returns the layout only. The caller places the chart off `left`/`right`,
    which are measured from the real label extents rather than from the radius,
    because a ten-character name reaches further than the ring does.
    """
    rank = sorted((languages or {}).items(), key=lambda kv: -kv[1])
    total = sum(v for _, v in rank)
    if not rank or not total:
        return None

    n = min(max(cats, 4), 8)
    head = rank if len(rank) <= n else rank[:n - 1]
    tail = rank[len(head):]
    # `other` takes its own rank rather than the end of the ring: folded, the
    # tail can outweigh the smallest language named above it, and a ring whose
    # radius stops falling clockwise is the one thing the angle was carrying.
    rows = sorted(head + ([("other", sum(v for _, v in tail))] if tail else []),
                  key=lambda kv: -kv[1])
    top = math.ceil(rows[0][1] / total * 10) / 10

    items = []
    for i, (name, byts) in enumerate(rows):
        a = math.radians(-90 + 360 * i / len(rows))
        ux, uy = math.cos(a), math.sin(a)
        share = byts / total
        # A language under a twentieth of a percent would print 0.0% beside a
        # ray the chart has drawn, which reads as nothing rather than as very
        # little.
        pct = f"{share * 100:.1f}%" if share >= 0.0005 else "<0.1%"
        anchor = "middle" if abs(ux) < 0.26 else "start" if ux > 0 else "end"
        lx, ly = _n(ux * (r + POLAR_NAME)), _n(uy * (r + POLAR_NAME))
        # Both lines read away from the centre, so the share never closes the
        # gap the name opened over the ring.
        dy = -POLAR_LINE if uy < 0 else POLAR_LINE
        w = max(len(name) * POLAR_NAME_FS, len(pct) * POLAR_PCT_FS) * c.MONO_ADVANCE
        off = -w / 2 if anchor == "middle" else 0 if anchor == "start" else -w
        items.append({
            "name": name, "share": share, "pct": pct, "anchor": anchor,
            "u": (_n(ux * r), _n(uy * r)),
            "lx": lx, "ly": ly, "dy": dy,
            "ray": (_n(ux * r * share / top), _n(uy * r * share / top)),
            "left": lx + off, "right": lx + off + w,
            "top": min(ly, ly + dy) - 9, "bottom": max(ly, ly + dy) + 4,
        })

    # The ring is its own floor on all four sides: a short label on one axis must
    # not pull the bounds inside the circle it sits outside of.
    def bound(key, fn, sign):
        return fn([sign * r] + [it[key] for it in items])

    return {
        "r": r, "max": top, "total": total, "items": items,
        "lead": max(range(len(items)), key=lambda i: items[i]["share"]),
        "left": bound("left", min, -1), "right": bound("right", max, 1),
        "top": bound("top", min, -1), "bottom": bound("bottom", max, 1),
    }


def polar_fit(languages, cats=POLAR_CATS, budget=None, ceiling=POLAR_R_MAX):
    """The widest ring that fits `budget` px of span, capped at `ceiling`.

    The caller's ceiling is the figure's own half-width, which is what holds the
    two at one size whatever the language mix does — fold a ninth language and
    the labels shorten, and without the cap the ring would simply grow past the
    slabs beside it.

    Under the cap the radius cannot be picked from the span by arithmetic: a
    ten-character name reaches further than the ring it labels does, and by a
    distance that does not shrink when the radius does. So it is stepped down
    from the ceiling instead, 2px at a time, which also keeps the five rings off
    the sub-pixel grid.
    """
    r0 = max(POLAR_R_MIN, min(POLAR_R_MAX, int(ceiling // 2) * 2))
    out = polar_layout(languages, cats, r0)
    if out is None or budget is None:
        return out
    r = r0 - 2
    while r >= POLAR_R_MIN and out["right"] - out["left"] > budget:
        out = polar_layout(languages, cats, r)
        r -= 2
    return out


def polar_body(theme, layout, cx, cy):
    """The ring centred on `(cx, cy)`.

    Drawing order is the type's: rings, spokes, every ray but the leader's, the
    leader, then the endpoints and labels over all of them.

    The leading language is the one datum this chart exists to deliver, so it is
    the ray that takes the accent — the slice's other use of it is the dot keying
    the focal slab, which rule 6 counts as a swatch rather than a second mark.
    The endpoint stays in ink: it is the structural head every ray carries, and
    the accent on both would spend the mark twice on one ray. Weight carries the
    leader as well — 2.4px against 2px, and a wider head — so the chart is still
    true where the hue is not.
    """
    lead = layout["lead"]
    grid = c.mix(theme.ink, theme.canvas, 0.1)

    def at(p):
        return _n(cx + p[0]), _n(cy + p[1])

    rings = []
    for i in range(POLAR_RINGS):
        # The outer ring is the terminus a ray is read against, so it is traced
        # like the spokes rather than dropped to gridline weight.
        paint = theme.faint if i == POLAR_RINGS - 1 else grid
        rings.append(f'<circle cx="{cx}" cy="{cy}" '
                     f'r="{_n(layout["r"] * (i + 1) / POLAR_RINGS)}" fill="none" '
                     f'stroke="{paint}" stroke-width="{CELL_EDGE}"/>')

    spokes, rays, heads, labels = [], [], [], []
    for i, it in enumerate(layout["items"]):
        focal = i == lead
        ux, uy = at(it["u"])
        spokes.append(f'<line x1="{cx}" y1="{cy}" x2="{ux}" y2="{uy}" '
                      f'stroke="{theme.faint}" stroke-width="{CELL_EDGE}"/>')

        rx, ry = at(it["ray"])
        # Round caps, so a language the stack rounds to a tenth of a percent
        # still leaves a visible dot at the centre instead of nothing at all.
        rays.append(
            f'<line x1="{cx}" y1="{cy}" x2="{rx}" y2="{ry}" '
            f'stroke="{theme.accent if focal else theme.dim}" '
            f'stroke-width="{POLAR_RAY_W + 0.4 if focal else POLAR_RAY_W}" '
            f'stroke-linecap="round"/>')
        heads.append(
            f'<circle cx="{rx}" cy="{ry}" r="{POLAR_HEAD + 1 if focal else POLAR_HEAD}" '
            f'fill="{theme.canvas}" stroke="{theme.ink if focal else theme.dim}" '
            f'stroke-width="1.2"/>')

        labels += [
            c.tx(_n(cx + it["lx"]), _n(cy + it["ly"]), it["name"],
                 fill=theme.ink if focal else theme.dim, family=c.MONO_STACK,
                 size=POLAR_NAME_FS, anchor=it["anchor"]),
            c.tx(_n(cx + it["lx"]), _n(cy + it["ly"] + it["dy"]), it["pct"],
                 fill=theme.faint, family=c.MONO_STACK, size=POLAR_PCT_FS,
                 anchor=it["anchor"]),
        ]

    ordered = [r for i, r in enumerate(rays) if i != lead] + [rays[lead]]
    return "\n".join(rings + spokes + ordered + heads + labels)


def _empty(theme):
    """A short slice when no roster is configured. Rule 10: degrade, don't crash."""
    body = "\n".join([
        c.heading(theme, HEAD_Y, "stack"),
        c.tx(c.TEXT_X, TOP_Y, "no stack configured", fill=theme.dim,
             family=c.MONO_STACK, size=13),
    ])
    return c.slice_svg(theme, c.to_grid(TOP_Y + 8), body,
                       title="Tools in rotation", desc="No stack is configured.")


def render(cfg, _data, theme):
    stack = cfg.get("stack") or {}
    if not stack:
        return _empty(theme)

    # Bottom to top, so the tray is index 0 and the layer order is the paint
    # order. Key order in stack.json is draw order, top category first.
    layers = [(name, list(tools.items())) for name, tools in reversed(list(stack.items()))]
    n = len(layers)

    out = foot_outline(FOOT_W, FOOT_D, FOOT_R)
    bounds = foot_bounds(out)
    front = max(x + y for x, y in out)
    back = min(x + y for x, y in out)

    # One grid, one cell size for every tool in the figure, set by the tightest
    # face. Sizing each face to its own width draws the same kind of object — a
    # tool — at a different size depending on which layer it landed on.
    side = max(tile_side(len(items), i == n - 1) for i, (_, items) in enumerate(layers))
    tile = tile_size(FOOT_W, FOOT_D, side)
    grids = [tile_cells(side, FOOT_W, FOOT_D, tile, len(items), i == n - 1)
             for i, (_, items) in enumerate(layers)]

    # gap = max(half the top face's screen height, 3 x thickness, the clearance
    # the cells need), on the 4px grid. Equal between every pair of levels;
    # shrinking one to fit the frame is the anti-pattern this rounding avoids.
    #
    # The third term governs here. A slab covers the back of the slab below it
    # at every spacing the type allows — (w+d)/2 of overlap against at most
    # 0.75(w+d)/2 of gap — so the cells are not placed on the face but in the
    # band the slab above leaves visible, and the gap has to open that band. A
    # slab's front corner hangs front/2 below its own level and the back-most
    # cell it must not cover sits back/2 below its, so the difference plus the
    # rise is what the level above has to clear. Only the covered layers are
    # measured: running their tools along the near border rather than over the
    # whole face is what buys the tighter stack, because the slab above is then
    # allowed to reach the lattice's middle diagonal.
    #
    # The rise taken is the ladder's tallest, not the roster's, so editing a
    # level never resizes the slice.
    clear = max([0.0] + [(front - min(x + y for x, y in cells)) / 2 + SLAB_H + RISE_MAX
                         for cells in grids[:-1]])
    gap = math.ceil(max((FOOT_W + FOOT_D) / 4, 3 * SLAB_H, clear) / 4) * 4

    # A category name is the widest thing in the label column; mono advances
    # 0.6em, so 15px type measures 9px a character. Rounding pulls the screen
    # extremes in off the corners, so the object's width is measured rather than
    # assumed.
    col_w = max(len(name) for name, _ in layers) * _round(LABEL_FS * c.MONO_ADVANCE)
    obj_l = out[bounds["left"]][0] - out[bounds["left"]][1]
    obj_r = out[bounds["right"]][0] - out[bounds["right"]][1]
    fig_w = obj_r - obj_l + LEADER + col_w

    # The languages ring takes the left of the slice and the figure what is left
    # of it. The two are the same subject at two scales — which layer the author
    # writes in, and which language inside it — so they share a heading rather
    # than a section each, and they are drawn at one size: the figure's own width
    # is the ring's ceiling, and the span left over only ever shrinks it from
    # there. The figure is the one held fixed, because a slab that resized with
    # the language mix would make two unrelated things move together.
    lang = polar_fit(cfg.get("languages"), POLAR_CATS,
                     c.CONTENT_R - c.TEXT_X - CHART_GAP - fig_w,
                     (obj_r - obj_l) / 2)
    chart_x = c.TEXT_X - lang["left"] if lang else c.TEXT_X
    fig_x = c.TEXT_X + (lang["right"] - lang["left"]) + CHART_GAP if lang else c.TEXT_X

    # The object and its column are centred together in what the ring left, so
    # the margins balance instead of the object hugging a rail.
    left = fig_x + max(0, (c.CONTENT_R - fig_x - fig_w) / 2)
    column = left + (obj_r - obj_l) + LEADER

    ox = left - obj_l
    oy = TOP_Y - back / 2 + (n - 1) * gap + SLAB_H
    pr = project(ox, oy)

    # Up the tray's left and right extremes to the underside of the top slab,
    # before every part so the parts cover them. Traced rather than enclosing,
    # so `faint` rather than the hairline.
    traces = []
    for key in ("left", "right"):
        px, py0 = pr(*out[bounds[key]], 0)
        py1 = pr(*out[bounds[key]], (n - 1) * gap)[1]
        traces.append(f'<line x1="{px}" y1="{py0}" x2="{px}" y2="{py1}" '
                      f'stroke="{theme.faint}" stroke-width="{CELL_EDGE}" '
                      f'stroke-dasharray="4,3"/>')

    parts, labels = [], []
    for i, (name, items) in enumerate(layers):
        z = i * gap
        focal = name == FOCAL
        # Index 0 is the tooling tray, and its cells are the figure's one shape
        # change: round against the squares the three layers above it carry.
        parts.append("\n".join([
            prism(pr, (0, 0, FOOT_W, FOOT_D, FOOT_R, z, SLAB_H), faces(theme, focal)),
            face_tiles(pr, ox, oy, z + SLAB_H, items, grids[i],
                       faces(theme, focal, 0.1), g=tile, round_cells=i == 0,
                       corner=_round(tile * FOOT_R / min(FOOT_W, FOOT_D)),
                       theme=theme),
        ]))

        # The dot sits on the slab's right extreme at mid-thickness. Equal
        # footprints put every dot on one x, so a horizontal leader runs out and
        # away from the object and no leader crosses a part or another leader.
        dx, dy = pr(*out[bounds["right"]], z + SLAB_H / 2)
        labels.append("\n".join([
            f'<circle cx="{dx}" cy="{dy}" r="{DOT_R}" '
            f'fill="{theme.accent if focal else theme.faint}"/>',
            f'<line x1="{dx + 9}" y1="{dy}" x2="{_n(column - 12)}" y2="{dy}" '
            f'stroke="{theme.faint}" stroke-width="{CELL_EDGE}"/>',
            # Centred on its leader: with no sublabel under it the name is the
            # whole label, and the heading already counts the tools.
            c.tx(_n(column), dy + 5, name.lower(), fill=theme.ink,
                 family=c.MONO_STACK, size=LABEL_FS, weight=700),
        ]))

    # The ring is centred against the figure's own span rather than hung off the
    # heading: the figure's mass is at the bottom of the slice and the ring's is
    # in the middle of its block, so aligning their tops leaves the whole lower
    # left of the panel empty.
    floor_y = max(pr(x, y, 0)[1] for x, y in out)
    chart = ""
    if lang:
        chart_y = _round((TOP_Y + floor_y - lang["top"] - lang["bottom"]) / 2)
        chart = polar_body(theme, lang, chart_x, chart_y)

    count = sum(len(items) for _, items in layers)
    roster = "; ".join(f"{name.lower()} ({len(items)}) " + ", ".join(t for t, _ in items)
                       for name, items in layers)
    body = "\n".join([
        c.heading(theme, HEAD_Y, "stack", counter=f"{count} tools"),
        *([chart] if chart else []), *traces, *parts, *labels,
    ])
    mix = ""
    if lang:
        shares = ", ".join(f"{it['name']} {it['pct']}" for it in lang["items"])
        mix = f" Languages by bytes: {shares} of {c.num(lang['total'])}."
    desc = (f"{count} tools on {n} layers of one stack, pulled apart along a "
            f"single axis and standing on their layers as brand marks. "
            f"Bottom to top: {roster}.{mix}")

    return c.slice_svg(theme, c.to_grid(floor_y + PAD_BELOW), body,
                       title="Tools in rotation", desc=desc)
