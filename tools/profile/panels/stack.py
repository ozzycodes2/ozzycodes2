"""`~/stack` as an exploded axonometric: one slab per category in stack.json.

Four rounded slabs in 2:1 dimetric, pulled apart along a single vertical axis.
Bottom to top they run tooling, cloud, platform, languages — tooling as the tray
the rest sits on, languages at the top because it is the layer the author
actually writes in, and the one the accent marks. Position along the axis is the
only relationship in the figure; there are no arrows, and no part rotates or
moves sideways.

Each category's tools stand on its own top face as raised cells, one per tool,
each carrying that tool's brand mark printed flat on the cell's lid. How tall a
cell stands is the tool's level 1-5 in stack.json, on a five-step ladder.

The marks are the one place this panel spends colour the design system never
declared. A logo is identified by its colour and twenty of them in one ink are
twenty silhouettes, so each is painted in its own brand hex and corrected until
it clears 3:1 on the cell it stands on. Several of those hexes are black, which
on the dark canvas is a hole rather than a brand — the correction is what keeps
the figure surviving the README's light/dark pairing.

What the figure costs: the twenty tool names. A logo and its name on one face is
a fourth level of detail and the type caps at three, so the names live in `desc`
— the README's alt text, and the only place a screen reader finds them.

Left of the figure and the same size as it, a polar ring gives languages by
bytes from languages.json: angle is rank, radius is share. The two are one
subject at two scales — which layer the author writes in, and which language
inside it — so they share this slice's heading rather than taking a section
each. This is the one panel spending two literal accents: the leading language's
ray, and the dot keying the focal slab's tint, which rule 6 counts as a swatch.

Both halves come from config, not from `data/`: the panel renders the same
figure on a machine that has never fetched.
"""
